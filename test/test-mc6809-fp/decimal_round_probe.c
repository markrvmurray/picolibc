int main(void) {
    char buf[40];
    int e = 0;
    for (unsigned i = 0; i < sizeof cases / sizeof cases[0]; i++) {
        if (cases[i].is_float)
            strfromf(buf, sizeof buf, cases[i].format, (float)cases[i].value);
        else
            strfromd(buf, sizeof buf, cases[i].format, cases[i].value);
        if (strcmp(buf, cases[i].expected) != 0) {
            printf("FAIL %u: %s %s: got \"%s\" want \"%s\"\n", i,
                   cases[i].is_float ? "float" : "double", cases[i].format, buf,
                   cases[i].expected);
            e++;
        }
    }
    printf("%d failures\n", e);
    return e != 0;
}
