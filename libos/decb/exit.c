#include "decb-private.h"
#include <stdlib.h>

void *__decb_entry_sp;

/* Back to BASIC.  EXEC reached the program with a JSR, so the return address
 * is still on the stack it handed over; the start-up code saved that stack
 * pointer, and going back to it returns to BASIC from however deep in the
 * program exit() was called.  No ROM address is needed, and none is guessed. */
void
_exit(int status)
{
    (void)status;                       /* BASIC has nowhere to put it */
    __asm__ __volatile__("lds %0\n\trts" : : "m"(__decb_entry_sp));
    __builtin_unreachable();
}
