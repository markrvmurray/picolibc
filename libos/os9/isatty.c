#include "os9-private.h"
#include <unistd.h>

/* SS.Opt: the path's option section; byte 0 is the device type (PD.DTP),
 * 0 = SCF (a terminal or a pipe-like character device), 1 = RBF (a file). */
int
isatty(int fd)
{
    unsigned char opts[32];
    if (_os_getstt_buf(fd, OS9_SS_OPT, opts, sizeof opts) != 0) {
        __os9_errno(errno);
        return 0;
    }
    if (opts[0] != 0) {
        errno = ENOTTY;
        return 0;
    }
    return 1;
}
